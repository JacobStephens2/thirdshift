test('Paused, dropped, ungraded and rechecked Trials retain their details across live updates', async t => {
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  t.after(() => context.close());
  const page = await context.newPage();
  page.setDefaultTimeout(10000);
  const folder = join(home, '.thirdshift/evals/experiments', fixture.id);
  await rm(join(folder, 'trials'), { recursive: true, force: true });
  await rm(join(folder, 'results'), { recursive: true, force: true });
  const value = fixture.record('paused');
  value.pause_reason = 'Paused at a provider plan-limit warning';
  await fixture.save(home, value);
  await page.goto(`${origin}/experiments`);
  assert.match(await page.locator('#experiment-group-1').textContent(), /Paused/);
  await page.locator(`a[href="/experiments/${fixture.id}"]`).first().click();
  assert.match(await page.locator('main').textContent(), /thirdshift experiment issue-1020 --baseline v1.0 --suite code-review/);
  await page.locator('#experiment-bar > summary').click();
  await page.getByRole('button', { name: 'alpha', exact: true }).click();
  assert.match(await page.locator('#peek-content').textContent(), /Baseline/);
  assert.match(await page.locator('#peek-content').textContent(), /Candidate/);
  await page.keyboard.press('Escape');
  const waiting = fixture.result('alpha', 'candidate', 0);
  waiting.score.model = null;
  await mkdir(join(folder, 'results'), { recursive: true });
  const resultPath = join(folder, 'results', `${fixture.key('alpha', 'candidate', 0)}.json`);
  await writeFile(resultPath, JSON.stringify(waiting));
  await page.getByRole('button', { name: 'Candidate Trial 1: Not graded', exact: true }).waitFor();
  const graded = fixture.result('alpha', 'candidate', 0);
  value.rechecks = { [fixture.key('alpha', 'candidate', 0)]: [{ passed: false, wrong_finding: false, reason: 'Human found a missed requirement', recorded_at: '2026-10-24T13:00:00Z' }] };
  await writeFile(resultPath, JSON.stringify(graded));
  await fixture.save(home, value);
  await page.getByRole('button', { name: /Candidate Trial 1: Failed, borderline, rechecked/ }).click();
  assert.match(await page.locator('#peek-content').textContent(), /Human found a missed requirement/);
  const failedAttempt = fixture.result('gamma', 'baseline', 0);
  failedAttempt.outcome = 'void';
  failedAttempt.attempts[0].outcome = 'void';
  failedAttempt.attempts[0].void_cause = 'memory_cap';
  failedAttempt.attempts[0].cause = 'Killed by its memory cap';
  await writeFile(join(folder, 'results', `${fixture.key('gamma', 'baseline', 0)}.json`), JSON.stringify(failedAttempt));
  await page.getByRole('button', { name: 'Baseline Trial 1: Void', exact: true }).click();
  assert.match(await page.locator('#peek-content').textContent(), /memory_cap/);
  assert.match(await page.locator('.trial-row[data-task="gamma"]').textContent(), /dropped/);
  assert.equal(await page.locator('#experiment-bar').getAttribute('open'), '');
  await page.keyboard.press('Escape');
  await page.screenshot({ path: '/tmp/thirdshift-1020-laptop.png', fullPage: true });
  value.state = 'running';
  await fixture.save(home, value);
  await page.goto(`${origin}/experiments`);
  assert.match(await page.locator('#experiment-group-0').textContent(), /Running/);
  value.state = 'completed';
  value.verdict = fixture.finish(fixture.record()).verdict;
  value.verdict.verdict = 'fail';
  value.verdict.provisional_verdict = 'fail';
  await fixture.save(home, value);
  await page.locator('.experiment-row[data-tone="urgent"]').waitFor();
  assert.match(await page.locator('#experiment-group-1').textContent(), /Fail/);
});
