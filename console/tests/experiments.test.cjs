  await page.locator('#peek-content a').filter({ hasText: 'Session log' }).click();
  await page.getByText('Retained Trial evidence', { exact: true }).waitFor();
  await page.goBack();
  await fixture.results(home);
  await fixture.save(home, fixture.finish(fixture.record()));
  await page.getByRole('heading', { name: 'Waiting on you', exact: true }).waitFor({ timeout: 15000 });
  assert.match(await page.locator('main').textContent(), /Provisionally inconclusive/);
  assert.match(await page.locator('main').textContent(), /8 more Eval tasks/);
  assert.equal(await page.locator('[data-rechecks] > li:visible').count(), 5);
  await page.getByRole('button', { name: 'Show all 6', exact: true }).click();
  assert.equal(await page.locator('[data-rechecks] > li:visible').count(), 6);
  await page.getByRole('button', { name: 'Copy command', exact: true }).first().click();
  assert.match(await page.evaluate(() => navigator.clipboard.readText()), /^thirdshift recheck c{64} [a-f0-9]+--candidate--0 pass --reason/);
  await page.getByRole('button', { name: 'Show only their Eval tasks below', exact: true }).click();
  assert.equal(await page.locator('.trial-row[data-task]:visible').count(), 2);
  await page.getByRole('button', { name: /Candidate Trial 1: Passed.*wrong finding/ }).first().click();
  assert.match(await page.locator('#peek-content').textContent(), /Grader reason for alpha/);
  assert.match(await page.locator('#peek-content').textContent(), /alpha-blind-0/);
  assert.match(await page.locator('#peek-content').textContent(), /Waiting on your recheck/);
  assert.equal(await page.locator('#peek').evaluate(el => getComputedStyle(el).position), 'fixed');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.keyboard.press('Escape');
  assert.ok(await page.locator('#experiment-arms').evaluate(el => el.compareDocumentPosition(document.querySelector('#experiment-trials')) & Node.DOCUMENT_POSITION_FOLLOWING));
  assert.equal(await page.locator('main script').count(), 0);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
