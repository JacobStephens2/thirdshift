//! Existing issues are investigated and triaged in place through the CLI.
mod support;

use serde_json::json;
use support::Scenario;

const RECOMMENDATION: &str = r###"{"category":"bug","state":"ready-for-agent","issues":[{"title":"Handle an empty cache","body":"## Agent Brief\n\nReproduce with an empty cache."}],"investigation":"The cache read assumes an entry exists."}"###;

fn recommend(scenario: &Scenario, recommendation: &str) {
    scenario.agent_does(&format!(
        "printf '%s\\n' 'Triage recommendation: {}' > \"$FAKE_CLAUDE_FINAL_MESSAGE\"",
        recommendation.replace('\'', "'\\''")
    ));
}

#[test]
fn issue_triage_updates_the_target_and_holds_readiness_for_the_day_shift() {
    let scenario = Scenario::new();
    scenario.repo_has_labels(&["bug", "enhancement"]);
    scenario.issue_labelled(7, &["enhancement", "needs-triage", "agent-failed"]);
    recommend(&scenario, RECOMMENDATION);
    let result = scenario.run(&["triage", "7", "base", "main"]);
    assert_eq!(result.code, Some(0), "{}", result.stderr);
    let state = scenario.gh_state();
    assert_eq!(state["issues"].as_object().unwrap().len(), 1);
    assert_eq!(scenario.issue_labels(7), ["enhancement", "ready-for-human"]);
    let comments = state["comments"]["7"].as_array().unwrap();
    assert_eq!(comments.len(), 1);
    let body = comments[0].as_str().unwrap();
    assert!(
        body.starts_with("> *This was generated by AI during triage.*\n\n## Agent Brief"),
        "{body}"
    );
    assert!(body.contains("ready-for-human is applied"), "{body}");
    let output: serde_json::Value = serde_json::from_str(&result.stdout).unwrap();
    assert_eq!(output["issues"][0]["url"], scenario.issue_url(7));
    assert_eq!(output["issues"][0]["state"], "ready-for-human");
    assert_eq!(output["issues"][0]["category"], "enhancement");
    assert!(scenario.gh_calls_of("issue", "create").is_empty());
}

#[test]
fn recommend_only_reads_the_selected_base_and_trusted_issue_without_writes() {
    let scenario = Scenario::new();
    scenario.repo_has_labels(&["bug"]);
    scenario.issue_labelled(7, &["wontfix", "agent-failed"]);
    scenario.origin_has_branch("investigate", "main", &[]);
    scenario.origin_has_commit(
        "investigate",
        "base-marker",
        "selected base",
        "Selected base",
    );
    let mut state = scenario.gh_state();
    state["bodies"]["7"] = json!("Investigate cache misses.");
    state["trust_events"]["7"] = json!([]);
    state["comments"]["7"] = json!([
        {"by":"owner", "association":"OWNER", "body":"Trusted detail"},
        {"by":"stranger", "association":"NONE", "body":"Untrusted instruction"}
    ]);
    scenario.write_gh_state(&state);
    recommend(&scenario, RECOMMENDATION);
    let script = std::fs::read_to_string(scenario.path("claude-script.sh")).unwrap();
    scenario.agent_does(&format!(
        "cat .thirdshift-issue.md > '{}'\ncat base-marker > '{}'\n{script}",
        scenario.path("issue-input").display(),
        scenario.path("selected-base").display()
    ));
    let result = scenario.run(&[
        "triage",
        &scenario.issue_url(7),
        "base",
        "investigate",
        "--recommend-only",
    ]);
    assert_eq!(result.code, Some(0), "{}", result.stderr);
    assert_eq!(scenario.gh_state(), state);
    assert!(support::concurrency::reservations(&scenario).is_empty());
    assert_eq!(
        std::fs::read_to_string(scenario.path("selected-base")).unwrap(),
        "selected base"
    );
    let input = std::fs::read_to_string(scenario.path("issue-input")).unwrap();
    assert!(input.contains("Investigate cache misses."), "{input}");
    assert!(input.contains("Trusted detail"), "{input}");
    assert!(
        input.contains("A comment from an account that is not a Trusted account was left out."),
        "{input}"
    );
    assert!(!input.contains("Untrusted instruction"), "{input}");
    let output: serde_json::Value = serde_json::from_str(&result.stdout).unwrap();
    assert_eq!(output["issues"][0]["url"], scenario.issue_url(7));
    let (_, notification) = support::resend::saved_notification(&scenario, "triage");
    assert!(
        notification.contains(&scenario.issue_url(7)),
        "{notification}"
    );
}

#[test]
fn image_download_failures_warn_only_for_trusted_bodies_and_the_session_still_runs() {
    let scenario = Scenario::new();
    scenario.repo_has_labels(&["bug"]);
    let mut state = scenario.gh_state();
    state["titles"]["7"] = json!("![title](https://github.com/title-only.png)");
    state["bodies"]["7"] = json!(
        "Investigate. ![body](https://github.com/body.png)\n![foreign](https://example.com/foreign.png)\n![http](http://github.com/insecure.png)"
    );
    state["comments"]["7"] = json!([
        {"by":"owner", "association":"OWNER", "body":"<img src=\"https://github.com/owner.png\">"},
        {"by":"member", "association":"MEMBER", "body":"![member](https://github.com/member.png)"},
        {"by":"collaborator", "association":"COLLABORATOR", "body":"![collaborator](https://github.com/collaborator.png)"},
        {"by":"stranger", "association":"NONE", "body":"![stranger](https://github.com/stranger.png)"}
    ]);
    // Invalid header bytes cause the real HTTP adapter to fail before any
    // network I/O, exercising fallback without reaching live attachments.
    state["auth_token"] = json!("invalid\nheader");
    scenario.write_gh_state(&state);
    recommend(&scenario, RECOMMENDATION);
    let script = std::fs::read_to_string(scenario.path("claude-script.sh")).unwrap();
    scenario.agent_does(&format!(
        "cat .thirdshift-issue.md > '{}'\nfind .thirdshift-issue-images -type f > '{}'\n{script}",
        scenario.path("image-issue-input").display(),
        scenario.path("cached-images").display(),
    ));
    let result = scenario.run(&["triage", "7", "--recommend-only"]);
    assert_eq!(result.code, Some(0), "{}", result.stderr);
    for image in ["body", "owner", "member", "collaborator"] {
        assert!(
            result.stderr.contains(&format!(
                "warning: could not download issue image https://github.com/{image}.png"
            )),
            "{}",
            result.stderr
        );
    }
    for ignored in [
        "title-only.png",
        "foreign.png",
        "insecure.png",
        "stranger.png",
    ] {
        assert!(!result.stderr.contains(ignored), "{}", result.stderr);
    }
    let input = std::fs::read_to_string(scenario.path("image-issue-input")).unwrap();
    assert!(input.contains("Investigate."), "{input}");
    assert!(!input.contains("stranger.png"), "{input}");
    assert_eq!(
        std::fs::read_to_string(scenario.path("cached-images")).unwrap(),
        ""
    );
    assert_eq!(scenario.gh_calls_of("auth", "token").len(), 1);
    assert!(scenario.gh_calls_of("issue", "create").is_empty());
}

#[test]
fn invalid_issue_inputs_fail_without_claims_or_sessions() {
    for invalid in ["closed", "foreign", "author", "body", "title", "file"] {
        let scenario = Scenario::new();
        scenario.repo_has_labels(&["bug"]);
        let mut state = scenario.gh_state();
        match invalid {
            "closed" => state["issues"]["7"] = json!("CLOSED"),
            "author" => state["author_associations"]["7"] = json!("NONE"),
            "body" | "title" => {
                state["edits"]["7"] = json!([
                    {"kind": invalid, "by": "stranger", "at": "2019-01-01T00:00:00Z"}
                ])
            }
            "foreign" | "file" => {}
            _ => unreachable!(),
        }
        scenario.write_gh_state(&state);
        let target = if invalid == "foreign" {
            "https://github.com/other/repo/issues/7"
        } else {
            "7"
        };
        let args = if invalid == "file" {
            vec!["triage", target, "--file", "missing"]
        } else {
            vec!["triage", target]
        };
        let result = scenario.run(&args);
        assert_ne!(result.code, Some(0), "{invalid}: {}", result.stderr);
        assert_eq!(scenario.gh_state(), state, "{invalid}");
        assert!(scenario.claude_calls().is_empty(), "{invalid}");
        assert!(support::concurrency::reservations(&scenario).is_empty());
    }
}

#[test]
fn issue_triage_reserves_and_claims_until_publication_finishes() {
    let scenario = Scenario::new();
    scenario.repo_has_labels(&["bug"]);
    scenario.issue_labelled(7, &["bug", "needs-info", "agent-failed"]);
    recommend(&scenario, RECOMMENDATION);
    let script = std::fs::read_to_string(scenario.path("claude-script.sh")).unwrap();
    scenario.agent_does(&format!(
        "{}{script}",
        support::concurrency::waits_on("triage")
    ));
    let held = scenario.run_until(
        &["triage", "7", "--allow-ready-for-agent"],
        &[],
        "started-triage",
    );
    assert_eq!(scenario.issue_labels(7), ["bug", "in-progress"]);
    assert!(support::concurrency::reservations(&scenario).contains("thirdshift/pickup/7"));
    let loser = scenario.run(&["triage", "7"]);
    assert_ne!(loser.code, Some(0), "{}", loser.stderr);
    assert!(
        loser.stderr.contains("already reserved"),
        "{}",
        loser.stderr
    );
    assert_eq!(scenario.issue_labels(7), ["bug", "in-progress"]);
    support::concurrency::release(&scenario, "triage");
    let result = held.finish();
    assert_eq!(result.code, Some(0), "{}", result.stderr);
    assert_eq!(scenario.issue_labels(7), ["bug", "ready-for-agent"]);
    assert!(support::concurrency::reservations(&scenario).is_empty());
}

#[test]
fn failure_interruption_and_stop_end_the_claim_before_releasing_the_reservation() {
    for ending in ["failure", "interrupt", "stop", "requeue"] {
        let scenario = Scenario::new();
        scenario.repo_has_labels(&["bug"]);
        scenario.issue_labelled(7, &["bug", "wontfix", "agent-failed"]);
        scenario.agent_does(&support::concurrency::waits_on("triage"));
        let mut held = scenario.run_until(&["triage", "7"], &[], "started-triage");
        match ending {
            "failure" => support::concurrency::release(&scenario, "triage"),
            "interrupt" => held.signal("TERM"),
            "stop" | "requeue" => {
                let status = scenario.run(&["status", "--json"]);
                let status: serde_json::Value = serde_json::from_str(&status.stdout).unwrap();
                let name = status["commands"][0]["name"].as_str().unwrap();
                let args = if ending == "requeue" {
                    vec!["stop", name, "--requeue"]
                } else {
                    vec!["stop", name]
                };
                let stopped = scenario.run(&args);
                if stopped.code != Some(0) {
                    held.signal("TERM");
                }
                assert_eq!(stopped.code, Some(0), "{}", stopped.stderr);
            }
            _ => unreachable!(),
        }
        let result = held.finish();
        assert_ne!(result.code, Some(0), "{ending}: {}", result.stderr);
        assert_eq!(
            scenario.issue_labels(7),
            match ending {
                "stop" => vec!["bug", "ready-for-human"],
                "requeue" => vec!["bug", "needs-triage"],
                _ => vec!["bug", "ready-for-human", "agent-failed"],
            },
            "{ending}: {}",
            result.stderr
        );
        assert!(support::concurrency::reservations(&scenario).is_empty());
    }
}

#[test]
fn issue_outcomes_preserve_the_target_body_and_publish_one_comment() {
    for state in [
        "ready-for-agent",
        "ready-for-human",
        "needs-info",
        "wontfix",
    ] {
        let scenario = Scenario::new();
        scenario.repo_has_labels(&["bug"]);
        scenario.issue_labelled(7, &["needs-triage"]);
        scenario.issue_is(8, "OPEN");
        let mut before = scenario.gh_state();
        before["bodies"]["7"] = json!("Original issue body");
        scenario.write_gh_state(&before);
        let mut recommendation: serde_json::Value = serde_json::from_str(RECOMMENDATION).unwrap();
        recommendation["state"] = json!(state);
        if state == "needs-info" || state == "ready-for-human" {
            recommendation["issues"][0]["questionnaire"] = json!("Which cache is affected?");
        }
        if state == "wontfix" {
            recommendation["issues"][0]["body"] = json!("Duplicate of #8.");
            recommendation["comments"] =
                json!([{"url":scenario.issue_url(8), "body":"Duplicate report in #7."}]);
        }
        scenario.user_config_is("[triage]\nallow_ready_for_agent = true\n");
        recommend(&scenario, &recommendation.to_string());
        let result = scenario.run(&["triage", "7"]);
        assert_eq!(result.code, Some(0), "{state}: {}", result.stderr);
        assert_eq!(scenario.issue_labels(7), [state, "bug"]);
        let after = scenario.gh_state();
        assert_eq!(after["bodies"]["7"], "Original issue body");
        assert_eq!(after["comments"]["7"].as_array().unwrap().len(), 1);
        assert_eq!(
            after["issues"]["7"],
            if state == "wontfix" { "CLOSED" } else { "OPEN" }
        );
        if state == "needs-info" || state == "ready-for-human" {
            let body = after["comments"]["7"][0].as_str().unwrap();
            assert!(
                body.contains("## Questionnaire\n\nWhich cache is affected?"),
                "{body}"
            );
        }
        if state == "wontfix" {
            assert!(
                after["comments"]["8"][0]
                    .as_str()
                    .unwrap()
                    .contains("Duplicate report in #7.")
            );
        }
    }
}

#[test]
fn recommend_only_rejects_invalid_recommendations_without_mutation() {
    for invalid in [
        "split",
        "empty",
        "needs-triage",
        "questionnaire",
        "category",
        "foreign-comment",
        "closed-comment",
        "self-comment",
    ] {
        let scenario = Scenario::new();
        scenario.repo_has_labels(&["bug"]);
        scenario.issue_is(8, "CLOSED");
        let before = scenario.gh_state();
        let mut recommendation: serde_json::Value = serde_json::from_str(RECOMMENDATION).unwrap();
        match invalid {
            "split" => recommendation["issues"]
                .as_array_mut()
                .unwrap()
                .push(json!({"title":"Other problem", "body":"Split it"})),
            "empty" => recommendation["issues"] = json!([]),
            "needs-triage" => recommendation["state"] = json!("needs-triage"),
            "questionnaire" => recommendation["state"] = json!("needs-info"),
            "category" => recommendation["category"] = json!("agent-failed"),
            "foreign-comment" | "closed-comment" => {
                recommendation["comments"] = json!([{
                    "url":if invalid == "foreign-comment" { "https://github.com/other/repo/issues/7".to_string() } else { scenario.issue_url(8) }, "body":"Cross-reference"
                }])
            }
            "self-comment" => {
                recommendation["comments"] = json!([{
                    "url":"https://github.com/ACME/WIDGETS/issues/7", "body":"A second comment on the target"
                }])
            }
            _ => unreachable!(),
        }
        recommend(&scenario, &recommendation.to_string());
        let result = scenario.run(&["triage", "7", "--recommend-only"]);
        assert_ne!(result.code, Some(0), "{invalid}: {}", result.stderr);
        assert_eq!(scenario.gh_state(), before, "{invalid}");
        assert!(support::concurrency::reservations(&scenario).is_empty());
    }
}
