#[test]
fn readiness_requires_the_flag_or_user_config_permission() {
    for (config, flags, expected) in [
        ("", vec!["--allow-ready-for-agent"], "ready-for-agent"),
        (
            "[triage]\nallow_ready_for_agent = true\n",
            vec![],
            "ready-for-agent",
        ),
        (
            "[triage]\nallow_ready_for_agent = false\n",
            vec![],
            "needs-triage",
        ),
        (
            "[triage]\nallow_ready_for_agent = false\n",
            vec!["--allow-ready-for-agent"],
            "ready-for-agent",
        ),
    ] {
        let scenario = Scenario::new();
        scenario.user_config_is(config);
        scenario.repo_has_labels(&["Bug"]);
        scenario.agent_does(&recommendation_script(RECOMMENDATION));
        let mut args = vec!["triage"];
        args.extend(flags);
        let result = scenario.run_with_input(&args, REPORT);
        assert_eq!(result.code, Some(0), "{}", result.stderr);
        assert_eq!(scenario.issue_labels(8), ["Bug", expected]);
    }
}

#[test]
fn separate_problems_are_cross_linked_with_independent_labels_and_the_file_report() {
    let scenario = Scenario::new();
    scenario.repo_has_labels(&["bug", "enhancement"]);
    let report = "Cache fails.\n```\n</details>\n````\nProduction also needs a dashboard.\n";
    let path = scenario.path("original-report.txt");
    fs::write(&path, report).unwrap();
    let recommendation = serde_json::json!({
        "category": "bug", "state": "ready-for-agent",
        "issues": [
            {"title": "Handle cache miss", "body": "Confirmed with an empty cache."},
            {"title": "Inspect the production dashboard", "body": "Ask the operator to inspect it.",
             "category": "enhancement", "state": "ready-for-agent",
             "confirmation_blocked": "Production credentials are needed to confirm the dashboard problem."}
        ],
        "investigation": "Confirmed the cache failure locally; production is inaccessible."
    });
    scenario.agent_does(&recommendation_script(&recommendation.to_string()));
    let result = scenario.run(&[
        "triage",
        "--allow-ready-for-agent",
        "--file",
        path.to_str().unwrap(),
    ]);
    assert_eq!(result.code, Some(0), "{}", result.stderr);
    assert_eq!(scenario.issue_labels(8), ["bug", "ready-for-agent"]);
    assert_eq!(scenario.issue_labels(9), ["enhancement", "ready-for-human"]);
    let state = scenario.gh_state();
    let (_, notification) = saved_notification(&scenario, "triage");
    for (number, other) in [(8, 9), (9, 8)] {
        let body = state["bodies"][number.to_string()].as_str().unwrap();
        assert!(body.contains(report), "{body}");
        assert!(body.contains(path.to_str().unwrap()), "{body}");
        assert!(body.contains("`````text"), "{body}");
        let comments = state["comments"][number.to_string()].as_array().unwrap();
        let links = comments[0].as_str().unwrap();
        assert!(
            links.starts_with("This comment was generated by AI."),
            "{links}"
        );
        assert!(links.contains(&scenario.issue_url(other)), "{links}");
        assert!(
            notification.contains(&scenario.issue_url(number)),
            "{notification}"
        );
    }
    assert!(
        state["bodies"]["9"]
            .as_str()
            .unwrap()
            .contains("Production credentials are needed")
    );
}

