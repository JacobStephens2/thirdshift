#[test]
fn invalid_comment_targets_fail_before_any_issue_is_filed() {
    for target in [
        "https://github.com/elsewhere/widgets/issues/7".to_string(),
        "https://github.com/acme/other/issues/7".to_string(),
        "https://github.com/acme/widgets/issues/404".to_string(),
        "https://github.com/acme/widgets/issues/7".to_string(),
    ] {
        let scenario = Scenario::new();
        scenario.issue_is(7, "CLOSED");
        scenario.repo_has_labels(&["bug"]);
        let before = scenario.gh_state();
        let recommendation = serde_json::json!({
            "category": "bug", "state": "needs-triage",
            "issues": [{"title": "Separate new problem", "body": "Do not file before validation."}],
            "comments": [{"url": target, "body": "New evidence."}],
            "investigation": "The proposed existing issue cannot receive this Report."
        });
        scenario.agent_does(&recommendation_script(&recommendation.to_string()));
        let result = scenario.run_with_input(&["triage"], REPORT);
        assert_ne!(result.code, Some(0), "{target}: {}", result.stderr);
        assert!(result.stdout.is_empty(), "{}", result.stdout);
        assert_eq!(scenario.gh_state(), before, "{target}");
    }
}

#[test]
fn a_comment_failure_still_notifies_issues_already_commented_on() {
    let scenario = Scenario::new();
    scenario.issue_is(8, "OPEN");
    scenario.gh_fails("issue comment 8");
    let report = "Cache fails.\n```\n</details>\n````\n";
    let path = scenario.path("report.txt");
    fs::write(&path, report).unwrap();
    let recommendation = serde_json::json!({
        "category": "bug", "state": "needs-triage", "issues": [],
        "comments": [
            {"url": scenario.issue_url(7), "body": "Confirmed the first cache failure."},
            {"url": scenario.issue_url(8), "body": "Confirmed a separate problem."}
        ],
        "investigation": "Two open issues cover the Report's separate problems."
    });
    scenario.agent_does(&recommendation_script(&recommendation.to_string()));
    let result = scenario.run(&["triage", "--file", path.to_str().unwrap()]);
    assert_ne!(result.code, Some(0));
    let state = scenario.gh_state();
    let comment = state["comments"]["7"][0].as_str().unwrap();
    assert!(comment.contains(report), "{comment}");
    assert!(comment.contains("`````text"), "{comment}");
    assert!(comment.contains(path.to_str().unwrap()), "{comment}");
    assert!(state["comments"]["8"].is_null());
    let (_, notification) = saved_notification(&scenario, "triage");
    assert!(
        notification.contains(&scenario.issue_url(7)),
        "{notification}"
    );
    assert!(
        notification.contains("already filed or commented on"),
        "{notification}"
    );
}

