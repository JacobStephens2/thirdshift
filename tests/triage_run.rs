mod support;

use std::fs;

use support::Scenario;
use support::concurrency::{release, waits_on};
use support::resend::{ResendStandIn, saved_notification};

const REPORT: &str = "Deploy canary fails when the cache is empty.\nPlease investigate.\n";
const RECOMMENDATION: &str = r#"{"category":"bug","state":"ready-for-agent","issues":[{"title":"Handle an empty cache","body":"Reproduce with an empty cache."}],"investigation":"The cache read assumes an entry exists."}"#;

fn recommendation_script(recommendation: &str) -> String {
    format!(
        "printf '%s\\n' 'Triage recommendation: {}' > \"$FAKE_CLAUDE_FINAL_MESSAGE\"",
        recommendation.replace('\'', "'\\''")
    )
}

#[test]
fn triage_comments_on_a_covering_issue_without_filing_or_changing_labels() {
    let scenario = Scenario::new();
    scenario.issue_labelled(7, &["enhancement", "ready-for-human", "in-progress"]);
    let before = scenario.gh_state();
    let recommendation = serde_json::json!({
        "category": "bug", "state": "ready-for-agent", "issues": [],
        "comments": [{"url": scenario.issue_url(7),
            "body": "Confirmed a cache miss reaches the unchecked read in cache.rs:42."}],
        "investigation": "Searched open issues; #7 already covers the empty-cache failure."
    });
    scenario.agent_does(&recommendation_script(&recommendation.to_string()));
    let result = scenario.run_with_input(&["triage"], REPORT);
    assert_eq!(result.code, Some(0), "{}", result.stderr);
    let after = scenario.gh_state();
    assert_eq!(after["issues"], before["issues"]);
    assert_eq!(after["labels"], before["labels"]);
    let comments = after["comments"]["7"].as_array().unwrap();
    assert_eq!(comments.len(), 1);
    let comment = comments[0].as_str().unwrap();
    assert!(
        comment.starts_with("This comment was generated by AI."),
        "{comment}"
    );
    assert!(comment.contains(REPORT), "{comment}");
    assert!(comment.contains("standard input"), "{comment}");
    assert!(comment.contains("cache.rs:42"), "{comment}");
    let output: serde_json::Value = serde_json::from_str(result.stdout.trim()).unwrap();
    assert_eq!(output["comments"][0]["url"], scenario.issue_url(7));
    let (_, notification) = saved_notification(&scenario, "triage");
    assert!(
        notification.contains(&scenario.issue_url(7)),
        "{notification}"
    );
}

